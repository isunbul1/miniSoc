"""SecurityAlert ORM model.

Represents alerts generated by the threat detection engine.
"""

from datetime import datetime, timezone

from sqlalchemy import DateTime, Enum as SQLEnum, ForeignKey, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.enums import AlertSeverity, AlertStatus
from app.db.database import Base


class SecurityAlert(Base):
    """A security alert raised from log analysis or detection rules."""

    __tablename__ = "security_alerts"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    severity: Mapped[AlertSeverity] = mapped_column(
        SQLEnum(AlertSeverity, native_enum=False, validate_strings=True),
        nullable=False,
        default=AlertSeverity.MEDIUM,
    )
    status: Mapped[AlertStatus] = mapped_column(
        SQLEnum(AlertStatus, native_enum=False, validate_strings=True),
        nullable=False,
        default=AlertStatus.OPEN,
    )
    source_ip: Mapped[str | None] = mapped_column(String(45), nullable=True, index=True)
    rule_id: Mapped[str | None] = mapped_column(String(50), nullable=True, index=True)
    incident_start: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    incident_key: Mapped[str | None] = mapped_column(String(150), nullable=True, index=True)
    detection_time: Mapped[datetime] = mapped_column(
        DateTime, default=lambda: datetime.now(timezone.utc), nullable=False
    )
    mitre_technique_id: Mapped[int | None] = mapped_column(
        Integer, ForeignKey("mitre_techniques.id"), nullable=True
    )

    # Relationship: alert -> technique
    mitre_technique: Mapped["MitreTechnique | None"] = relationship(
        "MitreTechnique", back_populates="alerts"
    )

    __table_args__ = (
        Index("ix_security_alerts_severity", "severity"),
        Index("ix_security_alerts_status", "status"),
        Index("ix_security_alerts_detection_time", "detection_time"),
    )

    def __repr__(self) -> str:
        return f"<SecurityAlert(id={self.id}, title={self.title}, severity={self.severity})>"
